FAKE_PYTHON = r'''#!/bin/sh
# "python -m venv DIR": a tool environment with fake pip (installs nothing), uv and pip-audit, each as FAKE_* says.
[ "$1" = "-m" ] && [ "$2" = venv ] || exit 2
[ "${FAKE_TOOLS:-ok}" = fail ] && { echo "ERROR: Could not find a version that satisfies uv" >&2; exit 1; }
mkdir -p "$3/bin"
printf '#!/bin/sh\n[ "%s" = pipfail ] && { echo "ERROR: No matching distribution found for uv" >&2; exit 1; }\nexit 0\n' "${FAKE_TOOLS:-ok}" > "$3/bin/python"
cat > "$3/bin/uv" <<'EOF'
#!/bin/sh
echo "$* | $(pwd) | ${UV_PYTHON_DOWNLOADS:-} ${UV_EXCLUDE_NEWER:-none}" >> "$FAKE_LOG"
case "$1" in
    lock) [ "${FAKE_UV:-ok}" = offline ] && { echo "error: Failed to fetch: https://pypi.org/simple/pypdf/" >&2; exit 2; }
          cp pyproject.toml "$FAKE_SEEN" ; exit 0 ;;
    export) out=""; prev=""; for a in "$@"; do [ "$prev" = "-o" ] && out="$a"; prev="$a"; done
            printf 'pypdf==7.0.1 \\\n    --hash=sha256:dddd\npyyaml==6.0.3 \\\n    --hash=sha256:eeee\n' > "$out"; exit 0 ;;
esac
exit 2
EOF
printf '#!/bin/sh\n[ "%s" = finding ] && { echo "Found 1 known vulnerability in 1 package"; exit 1; }\necho "No known vulnerabilities found"\n' "${FAKE_AUDIT:-ok}" > "$3/bin/pip-audit"
chmod +x "$3/bin/python" "$3/bin/uv" "$3/bin/pip-audit"
'''


@posix_only
class TestResolve:

    def _resolve(self, tmp_path, monkeypatch, **fake):
        project = tmp_path / "project"
        project.mkdir()
        (project / "pyproject.toml").write_text(PYPROJECT)
        (project / "uv.lock").write_text("version = 1\n")
        (project / "requirements-resolve.txt").write_text("uv==0.11.33 --hash=sha256:ffff\n")
        (project / "requirements-gui.txt").write_text("pypdf==7.0.0 \\\n    --hash=sha256:aaaa\npyyaml==6.0.3 \\\n"
                                                      "    --hash=sha256:eeee\n")
        python = executable(tmp_path / "python3", FAKE_PYTHON)
        monkeypatch.setenv("FAKE_LOG", str(tmp_path / "uv.log"))
        monkeypatch.setenv("FAKE_SEEN", str(tmp_path / "seen.toml"))
        monkeypatch.setenv("LCF_DEPS_NOW", "2026-11-10T00:00:00Z")
        monkeypatch.setenv("UV_EXCLUDE_NEWER", "2020-01-01T00:00:00Z")   # a stray setting never replaces pyproject's
        monkeypatch.delenv("LCF_OFFLINE", raising=False)
        for key, value in fake.items():
            monkeypatch.setenv(f"FAKE_{key.upper()}", value)
        out = tmp_path / "work" / "fresh.txt"
        code = fresh_deps.main(["resolve", "--project", str(project), "--work", str(tmp_path / "work"),
                                "--out", str(out), "--extra", "gui", "--python", str(python)])
        return code, out, project

    def test_the_newest_set_is_locked_in_a_copy_exported_and_audited(self, tmp_path, monkeypatch, capsys):
        code, out, project = self._resolve(tmp_path, monkeypatch)
        said = capsys.readouterr().out
        assert code == 0 and "pypdf==7.0.1" in out.read_text(), said
        calls = (tmp_path / "uv.log").read_text().splitlines()
        assert calls[0].startswith("lock --upgrade --python ") and f"| {tmp_path / 'work' / 'project'} |" in calls[0]
        assert calls[0].endswith("never none"), "no Python download, no stray exclude-newer"
        assert calls[1].startswith("export --frozen --format requirements-txt --no-dev --extra gui --no-emit-project")
        # the copy, not the shipped project, lost the exception the cooldown has passed
        assert "filelock" not in (tmp_path / "seen.toml").read_text()
        assert "filelock" in (project / "pyproject.toml").read_text()
        assert "newer than the tested lock: 1" in said and "pypdf 7.0.0 -> 7.0.1" in said

    @pytest.mark.parametrize("fake,code", [
        ({"tools": "fail"}, 3), ({"tools": "pipfail"}, 3), ({"uv": "offline"}, 3), ({"audit": "finding"}, 4),
    ])
    def test_no_tools_no_index_or_a_finding_means_the_tested_lock(self, tmp_path, monkeypatch, capsys, fake, code):
        assert self._resolve(tmp_path, monkeypatch, **fake)[0] == code, capsys.readouterr().out


