def executable(path, text):
    path.write_text(text)
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


# --- the cooldown and its exceptions ---------------------------------------------------------------------------------

def test_the_cutoff_is_now_minus_the_cooldown_in_utc(monkeypatch):
    monkeypatch.setenv("LCF_DEPS_NOW", "2026-11-08T21:00:00Z")
    five, seven = {"tool": {"uv": {"exclude-newer": "5 days"}}}, {"tool": {"uv": {"exclude-newer": "7 days"}}}
    assert fresh_deps.rfc3339(fresh_deps.cutoff(five)) == "2026-11-03T21:00:00Z"
    assert fresh_deps.cooldown_days({}) == 5 and fresh_deps.cooldown_days(seven) == 7


def test_an_exception_the_cooldown_has_passed_is_dropped_and_nothing_else_changes(tmp_path, monkeypatch):
    (tmp_path / "pyproject.toml").write_text(PYPROJECT)
    monkeypatch.setenv("LCF_DEPS_NOW", "2026-11-10T00:00:00Z")    # cutoff 2026-11-05T00:00:00Z
    assert fresh_deps.prune_exceptions(tmp_path) == ["filelock"]
    assert (tmp_path / "pyproject.toml").read_text() == PYPROJECT.replace('filelock = "2026-11-04T18:37:11Z"\n', "")
    monkeypatch.setenv("LCF_DEPS_NOW", "2026-11-20T00:00:00Z")
    assert fresh_deps.prune_exceptions(tmp_path) == ["pypdf", "openai"]
    assert "[tool.uv.exclude-newer-package]\n# taken inside the cooldown on purpose\n\n[build-system]" in \
        (tmp_path / "pyproject.toml").read_text()
    assert fresh_deps.prune_exceptions(tmp_path) == []


