# --- pip-audit as security.yml runs it ------------------------------------------------------------------------------

EXPORT = textwrap.dedent('''\
    # This file was autogenerated by uv via the following command:
    pypdf==7.0.0 \\
        --hash=sha256:aaaa
    soupsieve==2.10 ; python_full_version < '3.11.5' \\
        --hash=sha256:bbbb
    soupsieve==4.0 ; python_full_version >= '3.11.5' \\
        --hash=sha256:cccc
    ''')


@posix_only
@pytest.mark.parametrize("answer,code", [
    ("echo 'No known vulnerabilities found'; exit 0", 0),
    ("echo 'Found 1 known vulnerability in 1 package'; echo 'pypdf 7.0.0 PYSEC-0000-0'; exit 1", 4),
    ("echo 'ERROR: connection refused' >&2; exit 1", 5),
])
def test_the_audit_tells_a_finding_from_an_audit_that_could_not_run(tmp_path, answer, code):
    tool = executable(tmp_path / "pip-audit", f'#!/bin/sh\necho "$*" >> "{tmp_path}/audit.log"\n{answer}\n')
    work = tmp_path / "work"
    work.mkdir()
    (work / "req.txt").write_text(EXPORT)
    assert fresh_deps.audit(work / "req.txt", tool) == code
    calls = (tmp_path / "audit.log").read_text().splitlines()
    assert "--no-deps --disable-pip --desc on" in calls[0]
    if code == 0:
        # markers dropped, a name pinned twice in a second file (pip-audit refuses duplicates in one file)
        assert (work / "audit-main.txt").read_text() == "pypdf==7.0.0\nsoupsieve==2.10\n"
        assert (work / "audit-dups.txt").read_text() == "soupsieve==4.0\n"
        assert len(calls) == 2


