# --- the scheduled update run ----------------------------------------------------------------------------------------

def test_the_scheduled_update_run_lands_only_when_green():
    path = REPO_ROOT / ".github" / "workflows" / "deps-update.yml"
    text = path.read_text(encoding="utf-8")
    flow = yaml.safe_load(text)
    on = flow[True]   # YAML 1.1 reads the key "on" as true
    assert on["schedule"][0]["cron"] == "41 3 * * 2" and "workflow_dispatch" in on
    assert flow["permissions"] == {"contents": "read"}
    jobs = flow["jobs"]
    lock = "\n".join(step.get("run", "") for step in jobs["lock"]["steps"])
    assert "pip install --require-hashes --no-deps -r requirements-resolve.txt" in lock
    assert lock.index("fresh_deps.py prune-exceptions") < lock.index("uv lock --upgrade") < lock.index("uv export")
    assert "--exclude-newer" not in text, "the cooldown comes from pyproject.toml, so uv lock --check agrees"
    for name in ("requirements.txt", "requirements-gui.txt", "requirements-dev.txt", "requirements-resolve.txt"):
        assert f"-o {name}" in lock
    ci = yaml.safe_load((REPO_ROOT / ".github" / "workflows" / "ci.yml").read_text(encoding="utf-8"))
    assert jobs["test"]["strategy"]["matrix"] == ci["jobs"]["test"]["strategy"]["matrix"], "the full test matrix"
    assert "python -m pytest -ra" in [s.get("run") for s in jobs["test"]["steps"]]
    audit = "\n".join(step.get("run", "") for step in jobs["audit"]["steps"])
    assert "fresh_deps.py audit --requirements requirements-gui.txt" in audit
    # the pull request only after the update, the audit and every test job passed; to development, never merged
    propose = jobs["propose"]
    assert propose["needs"] == ["lock", "audit", "test"] and "always()" not in str(propose.get("if"))
    assert propose["permissions"] == {"contents": "write", "pull-requests": "write"}
    run = propose["steps"][-1]["run"]
    assert "gh pr create --base development" in run and "push --force origin HEAD:refs/heads/deps/update" in run
    assert "merge" not in run.replace("merged automatically", "").replace("Review and merge by hand", "")
    assert re.findall(r"\$\{\{ secrets\.(\w+)", text) == []
    for job in jobs.values():
        for step in job["steps"]:
            if "uses" in step:
                assert re.fullmatch(r"[\w./-]+@[0-9a-f]{40}", step["uses"]), step["uses"]
            if step.get("uses", "").startswith("actions/checkout@"):
                assert step["with"]["persist-credentials"] is False
